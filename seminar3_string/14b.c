#include <stdio.h>    // для fopen, fclose, fgetc, fputc, printf
#include <stdlib.h>   // для atoi, exit

// Функция шифрует один символ c, сдвигая его на k позиций по алфавиту
char caesar(char c, int k)
{
    // Если символ — заглавная буква A..Z
    if (c >= 'A' && c <= 'Z')
        // сдвигаем в пределах A..Z: 'A' + (номер буквы + k) % 26
        return 'A' + (c - 'A' + k) % 26;

    // Если символ — строчная буква a..z
    if (c >= 'a' && c <= 'z')
        // сдвигаем в пределах a..z
        return 'a' + (c - 'a' + k) % 26;

    // Всё остальное (пробелы, знаки, цифры, переводы строк) не меняем
    return c;
}

// main принимает аргументы командной строки: argc — количество, argv — сами аргументы
int main(int argc, char *argv[])
{
    // Если аргументов не 4 (имя программы + вход + выход + ключ)
    if (argc != 4)
    {
        // печатаем подсказку, как пользоваться программой
        printf("Usage: %s <input> <output> <key>\n", argv[0]);
        // выходим с кодом ошибки 1
        return 1;
    }

    // Открываем входной файл (argv[1]) на чтение ("r")
    FILE *in = fopen(argv[1], "r");
    // Если fopen вернул NULL — открыть не удалось
    if (in == NULL)
    {
        // сообщаем, какой файл не открылся
        printf("Error: cannot open '%s'\n", argv[1]);
        // выходим с ошибкой
        return 1;
    }

    // Открываем выходной файл (argv[2]) на запись ("w")
    // Если файл существует — он будет перезаписан; если нет — создан
    FILE *out = fopen(argv[2], "w");
    // Если выходной файл не открылся
    if (out == NULL)
    {
        // сообщаем об ошибке
        printf("Error: cannot open '%s'\n", argv[2]);
        // закрываем уже открытый входной файл, чтобы не оставлять его висящим
        fclose(in);
        // выходим с ошибкой
        return 1;
    }

    // Преобразуем ключ (argv[3]) из строки в целое число
    int k = atoi(argv[3]);

    // Переменная для текущего символа.
    // Тип int — потому что fgetc возвращает int (чтобы можно было вернуть EOF = -1)
    int c;

    // Читаем файл по одному байту, пока не достигнем конца (EOF)
    while ((c = fgetc(in)) != EOF)
        // Шифруем символ и записываем его в выходной файл
        fputc(caesar(c, k), out);

    // Закрываем входной файл (освобождаем ресурсы)
    fclose(in);
    // Закрываем выходной файл (при этом сбрасывается буфер на диск)
    fclose(out);

    // Успешное завершение программы
    return 0;
}
